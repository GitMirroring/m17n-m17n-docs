#!/bin/bash
#							-*- coding: utf-8; -*-
# $1: target directory (usr/latex, ja/latex, or dev/latex)

umask 002
USR_JA_DEV=`dirname $1`
cp styles/m17n-lib.sty $1
cd $1
LATEX=pdflatex
if [ $USR_JA_DEV = "dev" ] ; then
  sed -e '/documentclass/ s/a4paper/a4paper,twoside/' \
      -e '/The m17n Library Module Index/,/pages/ d' \
      -e '/The m17n Library File Documentation/,/textprop_8c/ d' \
      -e '/The m17n Library Directory Documentation/,/dir_000001/ d' \
      -e 's/The m17n Library Page Documentation/Appendix/' \
      -e '/\\def\\doxynewunicodechar#1#2{/,/^  }/d' \
      -e '/newunicodechar/d' \
    < refman.tex > m17n-lib.tex
else
  echo -e '\\appendix' > app.tex
  sed -n -e '/input{m17n-config}/,/input{GFDL}/ p' \
      -e '/% Index/,$ p' < refman.tex >> app.tex
  sed -e '/documentclass/ s/a4paper/a4paper,twoside/' \
      -e '/input{m17n-config}/,/input{GFDL}/ d' \
      -e '/% Index/,$ d' \
      -e '/\\def\\doxynewunicodechar#1#2{/,/^  }/d' \
      -e '/addcontentsline/d' \
      -e '/newunicodechar/d' \
    < refman.tex > m17n-lib.tex
  cat app.tex >> m17n-lib.tex
  if [ $USR_JA_DEV = "ja" ] ; then
    for f in *.tex; do
      LC_ALL=ja_JP.UTF-8 sed -i -e 's/詳解/詳述/g' -e 's/構築/Generated by/g' $f;
    done
  fi
fi

# The following "for" loop fixes this kind of buggy warnings:
#   LaTeX Warning: Label `doc-define-members' multiply defined.
# Delete this part when a future doxygen fixes this bug.
for f in group__*.tex struct*.tex; do
  group="`basename $f .tex`"
  sed -i "s/label{\(doc-[^}]*\)}/label{${group}_\1}/g" $f
done

echo "## ${LATEX} (1st run with lesser log)"
if ! ${LATEX} -interaction=batchmode -halt-on-error m17n-lib.tex; then
  echo An error occured.  The last 20 lines of m17n-lib.log are:
  tail -20 m17n-lib.log
  exit 1
fi
makeindex m17n-lib.idx
echo "## ${LATEX} (2nd run with lesser log)"
if ! ${LATEX} -interaction=batchmode -halt-on-error m17n-lib.tex; then
  echo An error occured.  The last 20 lines of m17n-lib.log are:
  tail -20 m17n-lib.log
  exit 1
fi
echo "## ${LATEX} (3rd run with full log)"
if ! ${LATEX} m17n-lib.tex; then
  exit 1
fi

